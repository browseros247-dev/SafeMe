    /** Device-language list with English fallback. */
    fun blockKeywordsFor(languageCode: String?): List<String> =
        blockKeywordsByLanguage[languageCode?.trim()?.lowercase()] ?: blockKeywordsByLanguage.getValue("en")

    /** True when a catalog entry is a site domain rather than a plain keyword. */
    fun isDomainEntry(entry: String): Boolean = entry.contains(".") && !entry.contains(" ")

    /** Domain entries of the effective language list (URL-gate coverage). */
    fun domainsFor(languageCode: String?): List<String> =
        blockKeywordsFor(languageCode).filter(::isDomainEntry)

    /** Plain keyword entries of the effective language list. */
    fun keywordsFor(languageCode: String?): List<String> =
        blockKeywordsFor(languageCode).filterNot(::isDomainEntry)
